/**
 * Absolute URL on the canonical host, always with a trailing slash (next.config uses trailingSlash: true).
 * Every canonical, og:url, breadcrumb and schema URL must go through this helper.
 */
export function absoluteUrl(path: string = "/"): string {
  const [pathname, query] = path.split("?");
  const withLeading = pathname.startsWith("/") ? pathname : `/${pathname}`;
  const withTrailing = withLeading.endsWith("/") ? withLeading : `${withLeading}/`;
  return `${SEO_CONFIG.siteUrl}${withTrailing}${query ? `?${query}` : ""}`;
}

