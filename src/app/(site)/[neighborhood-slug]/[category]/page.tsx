// "апартаменти Казански" / "двустайни апартаменти Казански" landing pages – ISR, purged on admin listing changes
export const revalidate = 3600;

type Params = Promise<{ "neighborhood-slug": string; category: string }>;

async function resolve(params: Params) {
  const { "neighborhood-slug": neighborhoodSlug, category: segment } = await params;
  const data = await getLandingData();
  const neighborhood = data.neighborhoods.find((n) => n.slug === neighborhoodSlug);
  // The segment is a category ("apartamenti") or an apartment rooms page ("dvustaini-apartamenti")
  const room = roomLandingBySlug(segment);
  const category = room ? findApartmentCategory(data.categories) : data.categories.find((c) => c.slug === segment);
  if (!neighborhood || !category) notFound();

  // Only combinations with listings exist – no empty doorway pages; rooms pages must also differ from the apartments page
  const roomPages = isApartmentCategory(category) ? roomLandingsFor(data.listings, { neighborhoodId: neighborhood.id }, category.id) : [];
  if (room && !roomPages.some((r) => r.room === room)) notFound();
  const scoped = filterListings(data.listings, { neighborhoodId: neighborhood.id, categoryId: category.id, rooms: room });
  if (scoped.length === 0) notFound();

  const what = room ? ROOM_LANDINGS[room].plural : category.plural;
  const h1 = `${what} в ${neighborhood.name_bg}, Стара Загора`;
  const path = room ? neighborhoodRoomsPath(neighborhood, room) : neighborhoodCategoryPath(neighborhood, category);
  // Sale and rent can be mixed here; price wording switches to rent only when nothing is for sale
  const isRent = filterListings(scoped, { operationType: "sale" }).length === 0;
  return { data, neighborhood, category, room, roomPages, scoped, stats: computeListingStats(scoped), what, h1, path, isRent };
}

/** Called once per neighborhood generated by the parent segment */
export async function generateStaticParams({
  params,
}: {
  params: { "neighborhood-slug": string };
}): Promise<Array<{ category: string }>> {
  const { neighborhoods, categories, listings } = await getLandingData();
  const neighborhood = neighborhoods.find((n) => n.slug === params["neighborhood-slug"]);
  if (!neighborhood) return [];
  const apartments = findApartmentCategory(categories);
  return [
    ...categories
      .filter((c) => filterListings(listings, { neighborhoodId: neighborhood.id, categoryId: c.id }).length > 0)
      .map((c) => ({ category: c.slug })),
    ...(apartments
      ? roomLandingsFor(listings, { neighborhoodId: neighborhood.id }, apartments.id).map((r) => ({ category: ROOM_LANDINGS[r.room].slug }))
      : []),
  ];
}

export async function generateMetadata({ params }: { params: Params }): Promise<Metadata> {
  const { neighborhood, stats, what, h1, path, isRent } = await resolve(params);
  return buildMetadata({
    title: `${h1} – ${listingCountLabel(stats.count)}`,
    description: `${what} в ${neighborhoodLabel(neighborhood.name_bg)}, Стара Загора – обяви със снимки, цени и описание. ${statsSentence(stats, isRent)}`,
    path,
  });
}

export default async function NeighborhoodCategoryPage({ params }: { params: Params }) {
  const { data, neighborhood, category, room, roomPages, scoped, stats, what, h1, isRent } = await resolve(params);
  const filters = { neighborhoodId: neighborhood.id, categoryId: category.id, rooms: room ? [room] : undefined };
  const result = await searchPropertyListings(filters, 1, LANDING_LIMIT);

  const breadcrumbs = buildBreadcrumbs([
    { name: "Начало", path: "/" },
    { name: "Имоти", path: "/properties/" },
    { name: `Имоти в ${neighborhood.name_bg}`, path: neighborhoodPath(neighborhood) },
    { name: category.plural, path: neighborhoodCategoryPath(neighborhood, category) },
    ...(room ? [{ name: ROOM_LANDINGS[room].short, path: neighborhoodRoomsPath(neighborhood, room) }] : []),
  ]);

  const quickNav =
    roomPages.length > 0 ? (
      <RoomTypeNav
        label={`Апартаменти в ${neighborhood.name_bg} по брой стаи`}
        tiles={roomTiles(
          roomPages,
          {
            href: neighborhoodCategoryPath(neighborhood, category),
            listings: filterListings(data.listings, { neighborhoodId: neighborhood.id, categoryId: category.id }),
          },
          (r) => neighborhoodRoomsPath(neighborhood, r),
          room
        )}
      />
    ) : undefined;

  const otherCategories = data.categories
    .filter((c) => c.id !== category.id || room != null)
    .map((c) => ({ c, count: filterListings(data.listings, { neighborhoodId: neighborhood.id, categoryId: c.id }).length }))
    .filter(({ count }) => count > 0)
    .map(({ c, count }) => ({ href: neighborhoodCategoryPath(neighborhood, c), label: `${c.plural} в ${neighborhood.name_bg}`, count }));

  // Same rooms value / category in other neighborhoods (rooms pages only where they exist)
  const otherNeighborhoods = data.neighborhoods
    .filter((n) => n.id !== neighborhood.id)
    .map((n) => {
      const count = room
        ? roomLandingsFor(data.listings, { neighborhoodId: n.id }, category.id).find((r) => r.room === room)?.listings.length ?? 0
        : filterListings(data.listings, { neighborhoodId: n.id, categoryId: category.id }).length;
      return { n, count };
    })
    .filter(({ count }) => count > 0)
    .sort((a, b) => b.count - a.count)
    .map(({ n, count }) => ({
      href: room ? neighborhoodRoomsPath(n, room) : neighborhoodCategoryPath(n, category),
      label: `${what} в ${n.name_bg}`,
      count,
    }));

  const intro = [
    `${what} в ${neighborhoodLabel(neighborhood.name_bg)}, Стара Загора, предлагани от Nova Nest.`,
    statsSentence(stats, isRent),
    room ? areaRangeSentence(scoped) : "",
    "Свържете се с нас за оглед или за още информация за квартала.",
  ]
    .filter(Boolean)
    .join(" ");

  return (
    <LandingPage
      h1={h1}
      intro={intro}
      breadcrumbs={breadcrumbs}
      facts={statsFacts(stats, isRent)}
      quickNav={quickNav}
      properties={result.properties}
      total={result.total}
      allHref={buildPropertiesHref(filters)}
      linkGroups={[
        {
          title: `Още в ${neighborhood.name_bg}`,
          links: [{ href: neighborhoodPath(neighborhood), label: `Всички имоти в ${neighborhood.name_bg}` }, ...otherCategories],
        },
        { title: `${what} в други квартали`, links: otherNeighborhoods },
      ]}
      emptyTitle={`В момента няма ${what.toLowerCase()} в ${neighborhood.name_bg}`}
      emptyDescription="Оставете запитване и ще ви уведомим първи за нови оферти в квартала."
    />
  );
}
